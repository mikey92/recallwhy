// The join map: for every supplier, how many of its barcoded ship notices reach our item master as written, and
// how many under each barcode rule the Cartographer can prove (the same predicates as src/agents/cartographer.ts:
// leading-zero padding, a dropped check digit, and the model-proposed 10-digit core, drop_first:1 → drop_last:1 on
// our UPC). A rule counts for a supplier only if it reaches every one of that supplier's ship notices, as the
// Cartographer requires. Runs the SQL on the DuckDB stand-in over the committed data; no model, no credentials.
//   npx tsx scripts/join-map.ts   → eval/results/join-map.json and docs/JOIN-MAP.md
import { writeFileSync } from "node:fs";
import { Trace } from "../src/trace.ts";
import { DuckSampleRunner } from "../src/sql/duck.ts";

const RULES = [
  ["as written", "a.upc = s.upc"],
  ["leading-zero padding", "regexp_replace(a.upc, '^0+', '') = regexp_replace(s.upc, '^0+', '')"],
  ["dropped check digit", "a.upc = substr(s.upc, 1, 11)"],
  ["10-digit core (model-proposed)", "a.upc = substr(s.upc, 2, 10)"],
] as const;

const trace = new Trace({ quiet: true });
const sql = new DuckSampleRunner({ trace });
const r = await sql.run(
  `SELECT a.supplier_id AS supplier, COUNT(*) AS n, ${RULES.map(([, p], i) => `SUM(CASE WHEN ${p} THEN 1 ELSE 0 END) AS k${i}`).join(", ")}
   FROM supplier_portal.ship_notices a JOIN erp.skus s ON s.sku = a.sku
   WHERE a.upc IS NOT NULL AND a.upc <> '' GROUP BY a.supplier_id ORDER BY a.supplier_id`,
  { agent: "Cartographer", purpose: "join map: ship notices reached per supplier under each barcode rule" });
await sql.close();

const rows = r.rows.map((x) => {
  const n = Number(x.n), k = RULES.map((_, i) => Number(x[`k${i}`]));
  const proven = RULES.map(([name], i) => ({ name, i })).find(({ i }) => k[i] === n);
  return { supplier: String(x.supplier), notices: n, asWritten: k[0], rule: proven?.name ?? "none proven", reached: proven ? n : k[0] };
});
const total = rows.reduce((a, x) => a + x.notices, 0), raw = rows.reduce((a, x) => a + x.asWritten, 0), after = rows.reduce((a, x) => a + x.reached, 0);
const byRule = Object.fromEntries(RULES.map(([name]) => [name, rows.filter((x) => x.rule === name).length]));
const orphans = rows.filter((x) => x.reached < x.notices);
writeFileSync("eval/results/join-map.json", JSON.stringify({ sqlId: r.sqlId, total, asWritten: raw, afterRules: after, suppliers: rows.length, suppliersByRule: byRule, orphans: orphans.map((x) => ({ supplier: x.supplier, notReached: x.notices - x.reached })), rows }, null, 2) + "\n");
const pct = (a: number) => `${((100 * a) / total).toFixed(1)}%`;
writeFileSync("docs/JOIN-MAP.md", [
  "# Join map: supplier ship notices → our item master",
  "",
  "Generated by `npx tsx scripts/join-map.ts` (SQL on the committed data, DuckDB stand-in; the live runs run the same predicates in Zetaris). A rule counts for a supplier only when it reaches **every** barcoded ship notice of that supplier, the Cartographer's bar for adopting it.",
  "",
  `**Joined as the suppliers write them: ${raw.toLocaleString("en-US")} of ${total.toLocaleString("en-US")} barcoded ship notices (${pct(raw)}). After the proven per-supplier rules: ${after.toLocaleString("en-US")} (${pct(after)}).** ${orphans.length ? `Not reached: ${orphans.map((x) => `${x.supplier} (${x.notices - x.reached})`).join(", ")}.` : "No supplier left unexplained."}`,
  "",
  `Suppliers by rule: ${Object.entries(byRule).map(([k, v]) => `${k} ${v}`).join(" · ")}.`,
  "",
  "| Supplier | Barcoded ship notices | Reached as written | Rule that reaches all | Reached after |",
  "|---|---|---|---|---|",
  ...rows.map((x) => `| ${x.supplier} | ${x.notices} | ${x.asWritten} | ${x.rule} | ${x.reached} |`),
  "",
  "In the live example runs the Cartographer proves only the rules a case needs (SUP028 and SUP007: dropped check digit; SUP010: the 10-digit core Nemotron proposed) and Zetaris's data-quality rule names the suppliers it has not reached yet; see `docs/ZETARIS.md`.",
  "",
].join("\n"));
console.log(`join map: ${raw}/${total} as written → ${after}/${total} after proven rules; ${JSON.stringify(byRule)}`);
